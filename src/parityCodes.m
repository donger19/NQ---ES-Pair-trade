function codes = parityCodes()
%PARITYCODES Integer encodings shared with the Pine parity export.
%   TradingView's chart export is numeric only, so every categorical the
%   indicator emits is an int. This is the single definition of those
%   encodings - pine/nq_es_pair.pine's "Parity export" block and
%   tests/parityCheck.m must both agree with it.

codes.signal = struct( ...
    'none', 0, 'armed', 1, 'pending', 2, 'enter', 3, ...
    'exit', 4, 'stop', 5, 'reversal', 6, 'gap_blocked', 7);

% SignalEngine emits string signals; map them onto the Pine ints.
codes.signalFromName = containers.Map( ...
    {'', 'armed', 'pending', 'enter', 'exit', 'stop', ...
     'reversal_eligible', 'gap_blocked', 'disarmed'}, ...
    { 0,   1,       2,         3,        4,      5, ...
      6,                   7,             0});

% gateMask bit values (pine: gateMask, MATLAB: SignalEngine out.gates)
codes.gate = struct( ...
    'zInside',   1, ...   % |z| below the entry gate
    'beyondHS',  2, ...   % |z| >= zHardStop
    'chop',      4, ...
    'zVel',      8, ...   % |z velocity| > zVelMax
    'roc',      16, ...   % |NQ ROC| > rocMax
    'regime',   32, ...   % regime undefined or the two models disagree
    'calmVeto', 64, ...
    'gapBlock', 128, ...
    'confirm',  256, ...  % pending, confirmation bars not yet met
    'warmup',   512, ...  % resSd not yet valid
    'noConv',  1024, ...  % neither converging nor intertwined
    'inPos',   2048);

codes.state = struct( ...
    'FLAT', 0, 'CONVERGENCE_ARMED', 1, 'SIGNAL_PENDING', 2, ...
    'IN_POSITION', 3, 'TP_ZONE', 4, 'REVERSAL_ELIGIBLE', 5);
end
